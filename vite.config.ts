import { defineConfig } from "@lovable.dev/vite-tanstack-config";
import { readFileSync } from "node:fs";
import { resolve as resolvePath } from "node:path";
import type { Plugin } from "vite";
import { PRERENDERED_ROUTES } from "./src/data/prerender";

/**
 * `/.well-known/api-catalog` has no file extension, so a static server has no
 * MIME type for it. RFC 9727 asks for `application/linkset+json`, so the file
 * generated by scripts/generate-public-data.ts is served with that type.
 */
function wellKnownContentTypes(): Plugin {
  const types: Record<string, string> = {
    "/.well-known/api-catalog": "application/linkset+json; charset=utf-8",
  };
  return {
    name: "well-known-content-types",
    configureServer(server) {
      server.middlewares.use((req, res, next) => {
        const path = (req.url ?? "").split("?")[0] ?? "";
        const type = types[path];
        if (!type) return next();
        try {
          const body = readFileSync(
            resolvePath(process.cwd(), `public${path}`),
            "utf8",
          );
          res.setHeader("Content-Type", type);
          res.setHeader("Cache-Control", "public, max-age=300");
          res.end(body);
        } catch {
          next();
        }
      });
    },
  };
}

// Sandbox preview only: the preview proxy forwards the app under
// <port>-<sandbox id>.<sandbox host domain>, which Vite's dev server rejects as
// an unknown host unless it is allowlisted. Unset (normal development) leaves
// Vite's default localhost behaviour untouched.
const previewMode = process.env["BASE44_PREVIEW_MODE"] === "1";
const sandboxHostDomain = process.env["BASE44_SANDBOX_HOST_DOMAIN"];

/**
 * Hybrid rendering.
 *
 * TanStack Start renders every route on the server (Nitro: `cloudflare-module`
 * for deploy, `node-server` for the local preview build). The routes below are
 * pure content — the same HTML for every visitor, changed only by a commit — so
 * they are prerendered at build time (SSG) instead of rendered per request.
 *
 * Routes deliberately left out, and why:
 * - `/projects`: its loader reads the published catalogue from the database at
 *   request time, so a project an admin publishes appears without a rebuild.
 * - `/projects/$slug`: per-project metadata comes from that same runtime
 *   catalogue, so it stays SSR and answers with its own title/OG tags at once.
 * - `/blog`, `/blog/$slug`, `/auth`, `/admin/*`: request-dependent (database,
 *   session, `ssr: false`).
 *
 * `crawlLinks` stays off: the prerender list is explicit, so a newly linked
 * dynamic route can never be frozen into a static file by accident.
 */
/**
 * Only the Worker build prerenders.
 *
 * TanStack's prerender pass boots the built server through its preview shim,
 * which loads Nitro's `index.mjs` entry. That works with the Cloudflare module
 * build (`bun run build`) — the artifact that actually serves visitors — but
 * not with:
 *
 * - Nitro's `node-server` entry, whose module does not expose `fetch`; there
 *   every route answered `server.fetch is not a function` and 0 pages
 *   prerendered. `build:preview` is the local SEO/a11y harness, so it stays
 *   pure SSR.
 * - Nitro's `cloudflare-pages` target (the builder sets `CF_PAGES`), which
 *   emits its worker as `dist/_worker.js/index.js` instead of `index.mjs`.
 *   The shim cannot load it, every route answered Internal Server Error and
 *   the whole Pages build failed. That target renders the same routes on
 *   demand instead of freezing them at build time.
 */
const NITRO_TARGET =
  process.env["NITRO_PRESET"] ??
  (process.env["CF_PAGES"] ? "cloudflare-pages" : "cloudflare-module");
const SSG_ENABLED =
  NITRO_TARGET !== "node-server" && NITRO_TARGET !== "cloudflare-pages";

// `PRERENDERED_ROUTES` lives in src/data/prerender.ts so scripts/seo-check.ts
// reads the same list and never expects a static file for a server-rendered
// route.

export default defineConfig({
  tanstackStart: {
    // Redirect TanStack Start's bundled server entry to src/server.ts (our SSR error wrapper).
    // nitro/vite builds from this
    server: { entry: "server" },
    // `public/sitemap.xml` is generated from src/data/seo.ts by
    // scripts/generate-sitemap.ts in prebuild; Start's own sitemap would
    // overwrite it with a different shape.
    sitemap: { enabled: false },
    prerender: {
      enabled: SSG_ENABLED,
      crawlLinks: false,
      failOnError: true,
      autoStaticPathsDiscovery: false,
    },
    pages: SSG_ENABLED
      ? PRERENDERED_ROUTES.map((path) => ({
          path,
          prerender: { enabled: true, crawlLinks: false },
        }))
      : [],
  },
  vite: {
    plugins: [wellKnownContentTypes()],
    ...(previewMode && sandboxHostDomain
      ? { server: { allowedHosts: [`.${sandboxHostDomain}`] } }
      : {}),
    // The Supabase publishable keys are public (browser-safe) but the platform
    // secrets store delivers them as SUPABASE_URL / SUPABASE_PUBLISHABLE_KEY
    // (no VITE_ prefix). Vite only exposes VITE_-prefixed vars to the browser
    // bundle, so inject the public keys here via define; the client falls back
    // to process.env.SUPABASE_URL when import.meta.env.VITE_SUPABASE_URL is empty.
    // The service-role key is intentionally NOT defined — it must never reach
    // the browser.
    define: {
      "process.env.SUPABASE_URL": JSON.stringify(
        process.env["SUPABASE_URL"] ?? "",
      ),
      "process.env.SUPABASE_PUBLISHABLE_KEY": JSON.stringify(
        process.env["SUPABASE_PUBLISHABLE_KEY"] ?? "",
      ),
    },
  },
});
