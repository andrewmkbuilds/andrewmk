// Writes `src/data/scene-pool.generated.ts` — the slug/name/category index the
// ambient background wall draws from.
//
// Why generate it: `src/data/sceneTiles.ts` used to import `allProjects`, which
// pulled the whole portfolio dataset (every description, feature list and
// challenge) into the layout chunk that every route loads before it can
// hydrate. The wall only ever needs three fields, so they are extracted here at
// build time and the full records stay in the route chunks that render them.
//
// Run from the repository root:
//   bunx tsx scripts/generate-scene-pool.ts
//
// The output is committed (the sandbox dev server skips `predev`), and `predev`
// / `prebuild` regenerate it so adding a project to `portfolio.ts` is still
// enough to put it on the wall.

import { writeFileSync } from "fs";
import { dirname, resolve } from "path";
import { fileURLToPath } from "url";
import { allProjects } from "../src/data/portfolio";

// `import.meta.dir` is Bun-only; the Cloudflare/CI builder runs this through
// tsx on Node, where it is undefined and `resolve(undefined, …)` throws
// ERR_INVALID_ARG_TYPE. Derive the directory from the module URL instead.
const here = dirname(fileURLToPath(import.meta.url));

const seen = new Set<string>();
const rows: { slug: string; name: string; category: string }[] = [];

for (const project of allProjects) {
  if (!project.slug || !project.name || seen.has(project.slug)) continue;
  seen.add(project.slug);
  rows.push({
    slug: project.slug,
    name: project.name,
    category: project.category,
  });
}

const body = rows
  .map(
    (row) =>
      `  { slug: ${JSON.stringify(row.slug)}, name: ${JSON.stringify(row.name)}, category: ${JSON.stringify(row.category)} },`,
  )
  .join("\n");

const output = `// GENERATED by scripts/generate-scene-pool.ts — do not edit by hand.
//
// The ambient wall's draw pool: one row per project in \`portfolio.ts\`, in
// portfolio order, carrying only the three fields the wall renders. Run
// \`bunx tsx scripts/generate-scene-pool.ts\` (or \`bun run build\`) after adding a
// project.

export const SCENE_PROJECT_ROWS: {
  slug: string;
  name: string;
  category: string;
}[] = [
${body}
];
`;

writeFileSync(resolve(here, "../src/data/scene-pool.generated.ts"), output);
console.log(`scene pool: ${rows.length} projects`);
